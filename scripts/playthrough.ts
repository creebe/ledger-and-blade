// Writes readable transcripts of complete games to docs/playthroughs/, so the
// story can be judged the way a player experiences it.
// Run: npm run playthroughs [weeks]
import { mkdirSync, writeFileSync } from 'node:fs';
import { FACTS } from '../src/engine/data/facts';
import { NPCS } from '../src/engine/data/facts';
import { APPROACH_INFO, advanceWeek, canChoose, CLOCKS, dateLabel, FACTIONS, living, newGame, PROFESSIONS, type GameState } from '../src/engine';
import { botTurn } from './sim';

const weeks = Number(process.argv[2] ?? 16);
const SEEDS = [
  { seed: 1111, style: 'pragmatic (takes the first sensible option)' },
  { seed: 2222, style: 'curious (asks every question before deciding)' },
  { seed: 3333, style: 'contrarian (prefers the last option)' },
];

function chooserFor(style: string) {
  return (s: GameState, ev: GameState['pendingEvents'][number]) => {
    const ok = ev.choices.map((c, i) => ({ c, i })).filter(({ c }) => !canChoose(s, c));
    if (!ok.length) return 0;
    if (style.startsWith('curious')) return (ok.find(({ c }) => c.next && !c.detail) ?? ok[0]).i;
    if (style.startsWith('contrarian')) return ok[ok.length - 1].i;
    return (ok.find(({ c }) => c.effects.flag !== 'hobbs_share') ?? ok[0]).i;
  };
}

mkdirSync('docs/playthroughs', { recursive: true });
const index: string[] = ['# Sample playthroughs', '', 'Generated by `npm run playthroughs`. Each is a full game played by a bot with a different decision style. They are meant to be read like a player would experience them.', ''];

for (const { seed, style } of SEEDS) {
  const s = newGame(seed);
  const L: string[] = [];
  const chooser = chooserFor(style);
  L.push(`# Playthrough ${seed}: ${style}`, '');
  L.push(`Starting roster: ${living(s).map((m) => `${m.name} (${PROFESSIONS[m.profession].name})`).join(', ')}.`, '');
  let seen = 0;
  for (let w = 0; w < weeks && !s.gameOver; w++) {
    L.push(`## ${dateLabel(s.week)}`, '');
    // decisions made this week
    const evBefore = s.dispatches.length;
    const outBefore = new Set(s.missions.map((m) => m.id));
    botTurn(s, { minChance: 0.5, chooser });
    for (const d of s.dispatches.slice(evBefore).filter((d) => d.kind === 'story' || d.kind === 'info')) {
      L.push(`**Decision: ${d.title}**`, '');
      for (const b of d.body) L.push(`> ${b}`);
      L.push('');
    }
    for (const m of s.missions.filter((m) => !outBefore.has(m.id))) {
      const names = m.memberIds.map((id) => s.members.find((x) => x.id === id)!.name.split(' ')[0]);
      L.push(`**Dispatched** ${names.join(', ')} on "${m.contract.title}" (${m.contract.region}, threat ${m.contract.threat}, ${m.contract.reward}◉). Plan: ${m.approaches.map((a) => APPROACH_INFO[a].name).join(' → ')}.`, '');
    }
    const crowns = s.crowns;
    seen = s.dispatches.length;
    advanceWeek(s);
    // what happened at the end of the week
    for (const d of s.dispatches.slice(seen)) {
      if (d.kind === 'mission' && d.missionId) {
        const m = [...s.missions, ...s.history].find((x) => x.id === d.missionId);
        const r = m?.report;
        if (!m || !r) continue;
        L.push(`### Journal: ${m.contract.title} (${r.tier})`, '');
        if (r.outbound) L.push(`*${r.outbound.title}.* ${r.outbound.lines.join(' ')}`, '');
        for (const p of r.phases) {
          L.push(`*${p.phase}* (${APPROACH_INFO[p.approach].name}, ${Math.round(p.chance * 100)}%, ${p.result}). ${(p.story ?? []).join(' ')} ${p.lines.slice(1).join(' ')}`.trim(), '');
        }
        if (r.homeward) L.push(`*${r.homeward.title}.* ${r.homeward.lines.join(' ')}`, '');
        L.push(`Outcome: ${r.summary.join(' ')}`, '');
      } else if (['rival', 'roster', 'warning', 'economy', 'politics'].includes(d.kind) || (d.kind === 'story' && !d.body[0]?.startsWith('▸'))) {
        L.push(`- *${d.title}.* ${d.body.join(' ')}`);
      }
    }
    seen = s.dispatches.length;
    L.push('', `Treasury ${crowns} → ${s.crowns}◉ · Supplies ${s.supplies} · Intel ${s.intel} · Renown ${s.renown} · Heat ${s.heat}`, '');
  }
  L.push('## Where things stand', '');
  if (s.gameOver) L.push(`**Game over (${s.gameOver.reason}):** ${s.gameOver.text}`, '');
  L.push(`- Members: ${living(s).map((m) => `${m.name} (Lv ${m.level})`).join(', ')}`);
  const fallen = s.members.filter((m) => m.status === 'dead' || m.status === 'left');
  if (fallen.length) L.push(`- Gone: ${fallen.map((m) => `${m.name}: ${m.causeOfDeath}`).join('; ')}`);
  L.push(`- Standing: ${Object.values(FACTIONS).map((f) => `${f.short} ${s.factions[f.id].standing}`).join(', ')}`);
  L.push(`- Debt clocks: ${Object.entries(CLOCKS).map(([k, c]) => `${c.name} ${Math.round(s.clocks[k as keyof typeof s.clocks])}`).join(', ')}`);
  L.push(`- People: ${Object.entries(s.npcs).map(([k, n]) => `${NPCS[k as keyof typeof NPCS].name} (${n.attitude >= 0 ? '+' : ''}${n.attitude})`).join(', ')}`);
  L.push(`- Story facts: ${Object.keys(s.flags).filter((f) => s.flags[f as keyof typeof FACTS]).join(', ')}`);
  const file = `game-${seed}.md`;
  writeFileSync(`docs/playthroughs/${file}`, L.join('\n') + '\n');
  index.push(`- [${file}](${file}): ${style}${s.gameOver ? `, ended in week ${s.gameOver.week} (${s.gameOver.reason})` : `, ${weeks} weeks`}`);
}
writeFileSync('docs/playthroughs/README.md', index.join('\n') + '\n');
console.log(index.join('\n'));
