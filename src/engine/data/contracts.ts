export interface ContractTemplate {
  id: string;
  type: string;
  titles: string[];
  patrons: FactionId[];
  description: string;
  regions: string[];
  threat: [number, number];
  tags: TagId[];
  optionalTags?: { tag: TagId; chance: number; seasons?: Season[] }[];
  hidden?: TagId[][]; // each entry: candidate pool for one hidden tag
  phases: PhaseDef[];
  baseReward: number;
  perThreat: number;
  materials?: { id: MaterialId; min: number; max: number }[];
  onSuccess: ContractEffect;
  onFailure: ContractEffect;
  contestChance: number;
  minSquad: number;
  maxSquad: number;
  weight: number;
  requiresFlag?: FactId;
  story?: boolean;
  shady?: boolean;
  // story contracts: facts set by the outcome
  successFlag?: FactId;
  failFlag?: FactId;
  expireFlags?: FactId[]; // set if the contract is accepted but never sent
  expire?: { title: string; text: string };
  // where the expedition goes, how far and what for. Unset parts come from the region and threat
  expedition?: Partial<ContractExpedition>;
}

const P = (name: string, approaches: PhaseDef['approaches'], weight: number, danger: number, text: string): PhaseDef => ({
  name,
  approaches,
  weight,
  danger,
  text,
});

